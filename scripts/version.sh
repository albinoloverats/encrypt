#!/bin/sh
# Generate application and build metadata for this build.
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
VERSION_FILE="$ROOT/VERSION"
HEADER="$ROOT/src/misc.h"
NSIS="$ROOT/version.nsh"

CFLAGS=${1-}
CPPFLAGS=${2-}
BUILD_OS=${3-}

[ -f "$VERSION_FILE" ] || { echo "version: missing $VERSION_FILE" >&2; exit 1; }
VERSION=$(sed -e 's/[[:space:]]*$//' "$VERSION_FILE")
case "$VERSION" in
    ""|*[!A-Za-z0-9._+-]*)
        echo "version: invalid value in VERSION: $VERSION" >&2
        exit 1
        ;;
esac

# Prefer an explicit revision (useful for source archives), otherwise use Git.
if [ -z "${GIT_COMMIT-}" ]; then
    GIT_COMMIT=$(git -C "$ROOT" rev-parse --verify HEAD 2>/dev/null || printf 'unknown')
fi

# Detect the build host using native tools. BUILD_OS may be supplied explicitly
# by packagers or cross-build environments to override host detection.
if [ -z "$BUILD_OS" ]; then
    if command -v freebsd-version >/dev/null 2>&1; then
        BUILD_OS="FreeBSD $(freebsd-version)"
    elif command -v sw_vers >/dev/null 2>&1; then
        BUILD_OS="$(sw_vers -productName) $(sw_vers -productVersion)"
    elif command -v cmd.exe >/dev/null 2>&1; then
        WINDOWS_VERSION=$(cmd.exe /c ver 2>/dev/null | tr -d '\r' | sed -n 's/.*\[\(.*\)\].*/\1/p')
        BUILD_OS="Windows${WINDOWS_VERSION:+ $WINDOWS_VERSION}"
    elif [ -r /etc/os-release ]; then
        BUILD_OS=$(sed -n 's/^PRETTY_NAME=//p' /etc/os-release | head -n 1 | sed -e 's/^"//' -e 's/"$//' -e "s/^'//" -e "s/'$//")
    else
        BUILD_OS=$(uname -srm 2>/dev/null || uname -s 2>/dev/null || printf 'unknown')
    fi
fi
[ -n "$BUILD_OS" ] || BUILD_OS=unknown

# Preserve arbitrary quotes and backslashes as C string contents.
escape_c_string()
{
    printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

VERSION_ESCAPED=$(escape_c_string "$VERSION")
GIT_COMMIT_ESCAPED=$(escape_c_string "$GIT_COMMIT")
BUILD_OS_ESCAPED=$(escape_c_string "$BUILD_OS")
CFLAGS_ESCAPED=$(escape_c_string "$CFLAGS")
CPPFLAGS_ESCAPED=$(escape_c_string "$CPPFLAGS")

mkdir -p "$(dirname "$HEADER")"
tmp="$HEADER.tmp"
{
    echo "/* Generated by scripts/version.sh; do not edit. */"
    printf '#define ENCRYPT_VERSION "%s"\n' "$VERSION_ESCAPED"
    printf '#undef GIT_COMMIT\n'
    printf '#define GIT_COMMIT "%s"\n' "$GIT_COMMIT_ESCAPED"
    printf '#undef BUILD_OS\n'
    printf '#define BUILD_OS "%s"\n' "$BUILD_OS_ESCAPED"
    printf '#define ALL_CFLAGS "%s"\n' "$CFLAGS_ESCAPED"
    printf '#define ALL_CPPFLAGS "%s"\n' "$CPPFLAGS_ESCAPED"
} > "$tmp"
mv "$tmp" "$HEADER"

tmp="$NSIS.tmp"
{
    echo "; Generated by scripts/version.sh; do not edit."
    printf '!define PRODUCT_VERSION "%s"\n' "$VERSION_ESCAPED"
} > "$tmp"
mv "$tmp" "$NSIS"
